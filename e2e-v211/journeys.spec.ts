test('V211 hifz add/undo/toggle/pause survives closing; plan edits preserve the active target', async ({ page, context }) => {
  await setup(page, {hifzTarget: 3});
  await visibleButton(page, 'بدء الحفظ').click();
  await add(page, 2);
  const beforeToggle = await facts(page);
  await visibleButton(page, 'إظهار مقدار التجربة').click();
  await visibleButton(page, 'إخفاء مقدار التجربة').click();
  expect((await facts(page)).events).toEqual(beforeToggle.events);
  await visibleButton(page, 'تراجع عن آخر تكرار').click();
  await expect(page.getByLabel('عدد التكرارات المحفوظ', {exact: true})).toHaveText('١');
  await visibleButton(page, 'توقف واحفظ').click();
  await expect(page.getByRole('heading', {name: 'كل يوم، أقرب إلى وردك'})).toBeVisible();
  const paused = await facts(page);
  expect(paused.state!.sessions).toHaveLength(1);
  expect(paused.state!.sessions[0]).toMatchObject({count: 1, targetSnapshot: 3, state: 'paused'});
  const identity = await page.evaluate(() => localStorage.getItem('mulazama-v211-synthetic-db'));
  await page.close();
  const reopened = await context.newPage();
  await reopened.clock.setFixedTime(new Date('2026-11-11T09:00:00Z'));
  await reopened.goto('/v211.html');
  await visibleButton(reopened, 'متابعة الحفظ').click();
  expect(await reopened.evaluate(() => localStorage.getItem('mulazama-v211-synthetic-db'))).toBe(identity);
  await expect(reopened.getByLabel('عدد التكرارات المحفوظ', {exact: true})).toHaveText('١');
  await visibleButton(reopened, 'الإعدادات').click();
  await visibleButton(reopened, 'تعديل الخطة').click();
  await visibleButton(reopened, 'التالي: الخطة').click();
  await reopened.getByLabel('هدف تكرارات الحفظ').fill('1');
  await visibleButton(reopened, 'مراجعة الخطة').click();
  await visibleButton(reopened, 'تأكيد الخطة').click();
  await visibleButton(reopened, 'متابعة الحفظ').click();
  await expect(reopened.locator('.v211-counter-target')).toHaveText('من ٣ تكرارًا');
  await add(reopened, 2);
  const complete = await facts(reopened);
  expect(complete.state!.plan!.hifzTarget).toBe(1);
  expect(complete.state!.sessions[0]).toMatchObject({id: paused.state!.sessions[0].id, count: 3, targetSnapshot: 3, state: 'completed'});
  expect(complete.state!.completions.filter(item => item.effective)).toHaveLength(1);
  expect(complete.events.filter(event => event.command.type === 'add-repetition')).toHaveLength(4);
  expect(complete.events.filter(event => event.command.type === 'undo-repetition')).toHaveLength(1);
  expect(complete.outbox.every(item => item.status === 'pending')).toBe(true);
});

test('V211 adjacent linking has its own target/count and restores separately from hifz', async ({ page }) => {
  await setup(page, {prior: [1], hifzTarget: 2, linkTarget: 2});
  await visibleButton(page, 'بدء الحفظ').click();
  await add(page, 2);
  const hifz = (await facts(page)).state!.sessions[0];
  expect(hifz.rangeSnapshot).toEqual([{start: 8, end: 16}]);
  await visibleButton(page, 'الانتقال إلى التثبيت').click();
  await add(page);
  await visibleButton(page, 'توقف واحفظ').click();
  await expect(page.getByRole('heading', {name: 'كل يوم، أقرب إلى وردك'})).toBeVisible();
  await page.reload();
  await visibleButton(page, 'متابعة التثبيت').click();
  await expect(page.getByLabel('عدد التكرارات المحفوظ', {exact: true})).toHaveText('١');
  await add(page);
  const after = (await facts(page)).state!;
  expect(after.sessions.find(session => session.id === hifz.id)).toEqual(hifz);
  expect(after.sessions.find(session => session.kind === 'link')).toMatchObject({count: 2, targetSnapshot: 2, state: 'completed', previousRange: {start: 0, end: 8}, newRange: {start: 8, end: 16}});
  expect(after.completions).toHaveLength(1);
});

test('V211 Friday keeps one frozen range and Saturday transfers eligibility despite unfinished review', async ({ page }) => {
  await setup(page, {at: '2026-11-13T09:00:00Z', hifzTarget: 1, cycleDays: 1});
  await visibleButton(page, 'بدء الحفظ').click();
  await add(page);
  await visibleButton(page, 'اليوم').click();
  await visibleButton(page, 'فتح مراجعة الأسبوع').click();
  await visibleButton(page, 'بدء مراجعة الجمعة').click();
  await expect(visibleButton(page, 'تسجيل إكمال المراجعة')).toBeVisible();
  const frozen = (await facts(page)).state!.reviews[0];
  expect(frozen).toMatchObject({kind: 'friday', rangesSnapshot: [{start: 0, end: 8}], status: 'active'});
  await page.clock.setFixedTime(new Date('2026-11-13T10:00:00Z'));
  await visibleButton(page, 'اليوم').click();
  await visibleButton(page, 'بدء الحفظ').click();
  await add(page);
  await visibleButton(page, 'اليوم').click();
  await visibleButton(page, 'فتح مراجعة الأسبوع').click();
  await expect(page.getByText('اكتمل حفظ إضافي بعد تثبيت النطاق.', {exact: false})).toBeVisible();
  await page.reload();
  const friday = (await facts(page)).state!;
  expect(friday.reviews).toEqual([frozen]);
  expect(friday.tasks).toHaveLength(0);
  await page.clock.setFixedTime(new Date('2026-11-14T09:00:00Z'));
  await page.reload();
  await expect.poll(async () => (await facts(page)).state!.transferredCompletionIds.length).toBe(2);
  const saturday = (await facts(page)).state!;
  expect(saturday.reviews[0]).toEqual(frozen);
  expect(saturday.tasks.flatMap(task => task.ranges)).toEqual([{start: 0, end: 16}]);
  await page.reload();
  expect((await facts(page)).state!.tasks).toEqual(saturday.tasks);
  expect((await facts(page)).state!.transferredCompletionIds).toEqual(saturday.transferredCompletionIds);
});

test('V211 partial overdue taahud preserves remainder and requires explicit next-date confirmation', async ({ page }) => {
  await setup(page, {prior: [1], cycleDays: 1, anchor: '2026-11-08'});
  await visibleButton(page, 'عرض خطة التعاهد').click();
  await expect(page.getByRole('heading', {name: /المتأخرات/})).toBeVisible();
  const original = (await facts(page)).state!.tasks[0];
  await page.getByLabel('عدد الوحدات المنجزة').fill('2');
  await visibleButton(page, 'تسجيل المنجز').click();
  await expect(page.getByLabel('موعد التعاهد القادم')).toHaveValue('2026-11-12');
  let state = (await facts(page)).state!;
  expect(state.tasks).toHaveLength(1);
  expect(state.tasks[0]).toMatchObject({id: original.id, originalDueDate: '2026-11-08', dueDate: '2026-11-08', remainingRanges: [{start: 2, end: 8}]});
  expect(state.proposals[0]).toMatchObject({ranges: [{start: 0, end: 2}], status: 'pending'});
  await page.reload();
  await page.getByLabel('موعد التعاهد القادم').fill('2026-11-20');
  await visibleButton(page, 'تأكيد الموعد').click();
  state = (await facts(page)).state!;
  expect(state.tasks[0].dueDate).toBe(original.dueDate);
  expect(state.tasks[1]).toMatchObject({ranges: [{start: 0, end: 2}], dueDate: '2026-11-20', scheduleSource: 'manual'});
  expect(state.taahudCompletions).toHaveLength(1);
  await visibleButton(page, 'تحديث مهام التعاهد').click();
  expect((await facts(page)).state!.tasks).toEqual(state.tasks);
});

